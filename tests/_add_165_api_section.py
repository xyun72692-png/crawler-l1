new_section = """### 16.5 「用接口能省请求」这个说法怎么判（含实测反例）

网上常见一句话：

> 招聘站大量用 XHR/API 返回结构化数据，一个接口一次返回 20~50 条；
> 用 Playwright 监听 `page.on("response")` 找到接口，请求数能从 5000 降到 100~200。

**我的判断：方向对，但混了两件事，数字也不普适。**

#### ① 两件事必须拆开

| 说法 | 实质 | 能不能省请求 |
|---|---|---|
| "用 Playwright 监听 response 找接口" | **侦察手段**（一次性） | ❌ 不能，监听本身仍要渲染页面 |
| "找到接口后直接打接口" | **稳态抓取**（长期） | ✅ 能，省的是"每页只给 5 条"这种浪费 |

正确姿势：**Playwright 只在侦察时用一次，找到接口后改用 `requests` 直接打**。
否则只是把"500 个 HTML 请求"换成"500 次页面渲染 + 500 个接口响应"，请求数没降、成本反而涨
（浏览器启动、内存占用、headless 指纹更容易被识别）。

#### ② 我们自己的站就是反例（实测，不是我推论）

拿已存样本离线自查（零请求）：

```
_probe_wzrc.html        71,376 字节   卡片 5   页面声明总页数 949
_probe_wzrc_dw_p1.html  81,618 字节   卡片 5
```

**列表是服务端渲染的**：HTML 里直接就有 5 条完整岗位（标题/公司/薪资/时间/福利全在），不靠 XHR 填。
再看 2026-11-11 13:20 那次真站实测：

| 实验 | 结果 |
|---|---|
| `?…&page=1` | 200 / 83,099 字节 / **5 卡片** |
| `?…&page=1&pagesize=50` | 200 / 86,712 字节 / **仍是 5 卡片**（只多 1.8KB 分页链接） |

结论：**本站既没有列表 XHR，也不接受放大每页条数**。
所以"接口一次返 20~50 条"对本站**不成立**——它是"老 CMS 的典型"，不是"现代站点的典型"。

#### ③ 真正决定收益的四个问题

| # | 要查什么 | 若答案是… | 收益 |
|---|---|---|---|
| 1 | 列表数据在 **HTML 里** 还是 **XHR 里**？ | HTML 里 → 换接口无意义 | **0** |
| 2 | 接口一次能要多少条？支持 `limit`/`pageSize` 吗？ | 只能 10~20 条 | 小~中 |
| 3 | 接口要不要**签名/登录**（`sign`/`token`/`__zp_stoken__`）？ | 要 → 就是我们不做的 L3 | **0（放弃）** |
| 4 | 接口字段够不够，**还要不要逐条打详情**？ | 还要详情 → 请求数几乎不降 | ≈0 |

**第 4 条最容易被忽略**：5000 条岗位如果每条都要开详情页，那 5000 个请求一个都省不掉；
接口只省"列表页"那一层。

#### ④ 一个可以照做的验证配方（成本 1~3 个请求）

```
1) 先看 HTML 源码：列表页里有没有完整岗位字段？
   有 → 停，不必找接口（本站就是这种）
2) 打开 F12 → Network → XHR/Fetch → 翻一页
   · 有没有返回数组的请求？一条返回几条？
   · 请求头/参数里有没有 sign / token / 时间戳？
3) 命中后复制成 curl，去掉 Cookie 再打一次
   · 仍返回数据 → 无登录态，可用 requests 直接打
   · 401 或签名错 → L3，按原则不做
4) 对比三个数：items/响应、是否仍需详情、robots 是否允许该路径
```

判断公式（我的口径）：

```
省不省 =（接口每条数 ÷ HTML 每页数）×（1 − 仍需详情比例）
        再乘 0/1：要不要签名（要 = 0）
```

- 本站：`5 ÷ 5 = 1`，且 `pagesize` 无效 → **省不了，别折腾**
- 20 条/页的站：`20 ÷ 20 = 1` → 也省不了
- 真能省的是：**HTML 每页只给 5~10 条、接口能给 30~50 条、且不要签名**

#### ⑤ 一条那条说法没提的风险

**robots.txt 通常只写 HTML 路径，不写接口路径。**
换接口不等于"更合规"，反而可能绕过站点原本的抓取限制意图。
所以：**接口路径也要过一遍 `url_allowed()`**，不允许就不打——这条已写进 16.4 的不变原则里。

---

### 16.6 一句话总结"""

