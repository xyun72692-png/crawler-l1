def md5(p: Path) -> str:
    return hashlib.md5(p.read_bytes()).hexdigest().upper()


def apply(path: Path, edits, tag: str):
    src = path.read_text(encoding="utf-8")
    backup = BAK / ("%s_before_fix_%s%s" % (tag, datetime.now().strftime("%Y%m%d-%H%M%S"), path.suffix))
    BAK.mkdir(parents=True, exist_ok=True)
    shutil.copy2(path, backup)

    fails = []
    out = src
    for i, (old, new) in enumerate(edits, 1):
        n = out.count(old)
        if n != 1:
            fails.append((i, n, old.splitlines()[0][:70]))
            continue
        out = out.replace(old, new, 1)

    if fails:
        print("[FAIL] %s 以下 %d 处未命中，整体不写回：" % (path.name, len(fails)))
        for i, n, prev in fails:
            print("   #%d 命中 %d 次 | %s" % (i, n, prev))
        print("   备份在 %s" % backup)
        return False

    path.write_text(out, encoding="utf-8")
    print("[OK] %s  替换 %d 处 | %d 字节 | %d 行 | MD5 %s"
          % (path.name, len(edits), len(out.encode("utf-8")),
             len(out.split("\n")) - (1 if out.endswith("\n") else 0), md5(path)))
    print("     备份：%s" % backup.name)
    return True


def main():
    ok = True
    ok &= apply(PLAIN, PLAIN_EDITS, "plain")
    ok &= apply(FULL, FULL_EDITS, "full")
    return 0 if ok else 1


