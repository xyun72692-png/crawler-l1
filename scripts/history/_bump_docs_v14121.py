def apply(name, pairs):
    s = DOCS / name
    t = s.read_text(encoding="utf-8")
    before = len(t)
    hit, miss = 0, []
    for a, b in pairs:
        if a in t:
            t = t.replace(a, b, 1)
            hit += 1
        else:
            miss.append(a[:60])
    # 备份现役版本
    bak = BAK / ("v14121_before_" + name)
    if not bak.exists():
        bak.write_text(s.read_text(encoding="utf-8"), encoding="utf-8")
    # 写 docs 与桌面（逐字节同一份内容）
    s.write_text(t, encoding="utf-8")
    (DESK / name).write_text(t, encoding="utf-8")
    print("%-34s 替换 %d/%d  字符 %d → %d" % (name[:30], hit, len(pairs), before, len(t)))
    for m in miss:
        print("   !! 未命中：", m)
    print("   docs  MD5 %s  %d B" % (md5(s)[:16], s.stat().st_size))
    print("   桌面  MD5 %s  %d B" % (md5(DESK / name)[:16], (DESK / name).stat().st_size))
    print("   两处一致：", md5(s) == md5(DESK / name))


